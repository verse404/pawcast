let cachedMelbourne: AuSuburbEntry[] | null = null;
let cachedSydney: AuSuburbEntry[] | null = null;
let cachedShanghai: AuSuburbEntry[] | null = null;

export interface NearestSuburbMatch {
  suburb: AuSuburbEntry;
  distanceKm: number;
}

const POSTAL_ONLY_SUFFIX_RE =
  /(?:\b(?:po|lpo|bc|dc|mc|university|hospital|centre)\b|^north pole$)/i;

export function getAuSuburbsForCity(
  city: 'melbourne' | 'sydney' | 'shanghai'
): AuSuburbEntry[] {
  if (city === 'melbourne') {
    if (!cachedMelbourne) {
      cachedMelbourne = MELBOURNE_SUBURB_TUPLES.filter(
        ([name, postcode]) => postcode !== '9999' && name !== 'North Pole'
      ).map(([name, postcode, areaIdx, council, latitude, longitude]) => ({
        id: `mel-${postcode}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
        city: 'melbourne',
        name,
        postcode,
        area: MELBOURNE_AREAS[areaIdx] ?? 'Melbourne',
        council,
        latitude,
        longitude,
        timezone: 'Australia/Melbourne',
        featured:
          FEATURED_MEL.has(name) &&
          !(name === 'Melbourne' && postcode !== '3000'),
      }));
    }
    return cachedMelbourne;
  }
  if (city === 'sydney') {
    if (!cachedSydney) {
      cachedSydney = SYDNEY_SUBURB_TUPLES.map(
        ([name, postcode, areaIdx, council, latitude, longitude]) => ({
          id: `syd-${postcode}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
          city: 'sydney',
          name,
          postcode,
          area: SYDNEY_AREAS[areaIdx] ?? 'Sydney',
          council,
          latitude,
          longitude,
          timezone: 'Australia/Sydney',
          featured: FEATURED_SYD.has(name),
        })
      );
    }
    return cachedSydney;
  }
  if (!cachedShanghai) {
    cachedShanghai = SHANGHAI_SUBURB_TUPLES.map(
      ([name, postcode, areaIdx, council, latitude, longitude], idx) => ({
        id: `sh-${postcode}-${idx}-${name
          .split(' · ')[0]
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')}`,
        city: 'shanghai',
        name,
        postcode,
        area: SHANGHAI_AREAS[areaIdx] ?? 'Shanghai',
        council,
        latitude,
        longitude,
        timezone: 'Asia/Shanghai',
        featured: FEATURED_SH.has(name),
      })
    );
  }
  return cachedShanghai;
}

export function suburbToLocationPoint(
  sub: AuSuburbEntry,
  exactGpsCoords?: { latitude: number; longitude: number }
): LocationPoint {
  const cityPrefix =
    sub.city === 'melbourne'
      ? 'Melbourne'
      : sub.city === 'sydney'
        ? 'Sydney'
        : 'Shanghai';
  return {
    name: `${cityPrefix} · ${sub.name}`,
    region: `${sub.postcode} · ${sub.area}${sub.council ? ` (${sub.council})` : ''}`,
    latitude: exactGpsCoords ? exactGpsCoords.latitude : sub.latitude,
    longitude: exactGpsCoords ? exactGpsCoords.longitude : sub.longitude,
    timezone: sub.timezone,
    isCurrentDeviceLocation: Boolean(exactGpsCoords),
  };
}

export function computeSuburbDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const r = (d: number) => (d * Math.PI) / 180;
  const a =
    Math.sin(r(lat2 - lat1) / 2) ** 2 +
    Math.cos(r(lat1)) * Math.cos(r(lat2)) * Math.sin(r(lon2 - lon1) / 2) ** 2;
  return 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function formatSuburbDistance(distanceKm: number): string {
  if (distanceKm < 1) {
    const meters = Math.max(50, Math.round((distanceKm * 1000) / 50) * 50);
    return `${meters} m`;
  }
  return `${distanceKm.toFixed(1)} km`;
}

/**
 * Finds the nearest official Melbourne, Sydney, or Shanghai suburbs around GPS coordinates,
 * preferring real residential suburbs over postal-box sub-localities.
 */
export function findNearestAuSuburbs(
  latitude: number,
  longitude: number,
  limit = 8,
  maxRadiusKm = 110
): NearestSuburbMatch[] {
  const pool = [
    ...getAuSuburbsForCity('melbourne'),
    ...getAuSuburbsForCity('sydney'),
    ...getAuSuburbsForCity('shanghai'),
  ];
  const scored: Array<NearestSuburbMatch & { sortKey: number }> = [];
  for (const suburb of pool) {
    const distanceKm = computeSuburbDistanceKm(
      latitude,
      longitude,
      suburb.latitude,
      suburb.longitude
    );
    if (distanceKm <= maxRadiusKm) {
      const postalPenalty = POSTAL_ONLY_SUFFIX_RE.test(suburb.name) ? 3.5 : 0;
      scored.push({
        suburb,
        distanceKm,
        sortKey: distanceKm + postalPenalty,
      });
    }
  }
  scored.sort((a, b) => a.sortKey - b.sortKey);

  // Deduplicate identical postcode centroids within 150m so adjacent distinct suburbs appear cleanly
  const deduped: NearestSuburbMatch[] = [];
  for (const item of scored) {
    const sameCentroid = deduped.some(
      (d) =>
        d.suburb.city !== 'shanghai' &&
        d.suburb.postcode === item.suburb.postcode &&
        Math.abs(d.distanceKm - item.distanceKm) < 0.15
    );
    if (!sameCentroid) {
      deduped.push({ suburb: item.suburb, distanceKm: item.distanceKm });
    }
    if (deduped.length >= limit) break;
  }
  return deduped;
}

export function detectActiveRegion(
  latitude: number,
  longitude: number
): ActiveMetroRegion {
  if (computeSuburbDistanceKm(latitude, longitude, -37.8136, 144.9631) <= 105) {
    return 'melbourne';
  }
  if (computeSuburbDistanceKm(latitude, longitude, -33.8688, 151.2093) <= 105) {
    return 'sydney';
  }
  if (computeSuburbDistanceKm(latitude, longitude, 31.21, 121.47) <= 105) {
    return 'shanghai';
  }
  return 'global';
}

export function isAustralianRegion(region: ActiveMetroRegion): boolean {
  return region === 'melbourne' || region === 'sydney';
}
